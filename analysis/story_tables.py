"""Tables and the figure for the syndication experiment and the source contest.

Every number in the generated files is read from a committed raw output:
results/musique_syndication/verdict.json, written by
analysis/syndication_analysis.py from the per-record reader outputs, and
results/gate1/contest.csv, written by experiments/gate1_mechanism.py. Nothing
is transcribed by hand, so rerunning this script after rerunning either
experiment regenerates the manuscript's numbers.
"""
from __future__ import annotations

import csv
import json
import os
